class StoreManager {
  private db: DatabaseSchema;

  constructor() {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    if (!fs.existsSync(UPLOADS_DIR)) {
      fs.mkdirSync(UPLOADS_DIR, { recursive: true });
    }

    if (fs.existsSync(DB_FILE)) {
      try {
        const raw = fs.readFileSync(DB_FILE, 'utf-8');
        this.db = JSON.parse(raw) as DatabaseSchema;
      } catch {
        this.db = createInitialSeed();
        this.persist();
      }
    } else {
      this.db = createInitialSeed();
      this.persist();
    }
  }

  public getState(): DatabaseSchema {
    return this.db;
  }

  public persist(): void {
    const tmpFile = `${DB_FILE}.tmp`;
    fs.writeFileSync(tmpFile, JSON.stringify(this.db, null, 2), 'utf-8');
    fs.renameSync(tmpFile, DB_FILE);
  }

  public transaction<T>(fn: (db: DatabaseSchema) => T): T {
    const result = fn(this.db);
    this.persist();
    return result;
  }
}

export const store = new StoreManager();
